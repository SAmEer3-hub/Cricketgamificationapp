package com.example.fantasycricketapp.data.data.remote



import com.example.fantasycricketapp.utils.ApiConstants
import okhttp3.OkHttpClient
import okhttp3.logging.HttpLoggingInterceptor
import retrofit2.Retrofit
import retrofit2.converter.gson.GsonConverterFactory
import java.util.concurrent.TimeUnit

/**
 * CricApiClient — Singleton that creates and holds the Retrofit instance.
 *
 * Uses 'object' so it is created once and reused everywhere.
 * Creating Retrofit/OkHttp is expensive — never create them per-request.
 *
 * Components:
 *   OkHttpClient   → handles actual HTTP connections, timeouts, logging
 *   GsonConverter  → automatically converts JSON ↔ Kotlin data classes
 *   Retrofit       → generates CricApiService implementation
 */
object CricApiClient {

    // ── OkHttp logging interceptor ──
    // Shows full request/response in Logcat during development
    // Tag: "OkHttp" in Logcat filter
    private val loggingInterceptor = HttpLoggingInterceptor().apply {
        // BODY = log full request + response body (use NONE in production)
        level = HttpLoggingInterceptor.Level.BODY
    }

    // ── OkHttp client with timeouts ──
    private val okHttpClient = OkHttpClient.Builder()
        .addInterceptor(loggingInterceptor)
        .connectTimeout(ApiConstants.CONNECT_TIMEOUT, TimeUnit.SECONDS)
        .readTimeout(ApiConstants.READ_TIMEOUT, TimeUnit.SECONDS)
        .writeTimeout(ApiConstants.WRITE_TIMEOUT, TimeUnit.SECONDS)
        .build()

    // ── Retrofit instance ──
    private val retrofit: Retrofit by lazy {
        Retrofit.Builder()
            .baseUrl(ApiConstants.BASE_URL)
            .client(okHttpClient)
            .addConverterFactory(GsonConverterFactory.create())
            .build()
    }

    // ── The actual service — generated by Retrofit ──
    val service: CricApiService by lazy {
        retrofit.create(CricApiService::class.java)
    }
}